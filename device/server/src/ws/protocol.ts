/**
 * デバイスとサーバーの取り決め。
 *
 * デバイス → サーバー: **バイナリのフレーム**（16kHz mono 16bit LE、80ms）
 * サーバー → デバイス: **JSON**（状態・文字）と**バイナリ**（鳴らす WAV）
 *
 * デバイス側に判断をさせないので、送るのは「いまどう見せるか」だけ。
 */

import type { Emotion } from "../speech/emotion.ts";

/** 画面の状態。ブラウザ版の 5 状態をそのまま移した。 */
export type DeviceState =
  | "idle" // 待機。時計を出す
  | "listening" // 聞き取り中
  | "thinking" // 考え中
  | "speaking" // 回答中
  /**
   * 追い質問の窓が開いている。ウェイクワード無しで続けられる。
   *
   * **黙って聞いている状態を作らない。** 画面に「続けてどうぞ」と出す。
   * 常時マイクが開いている機械なので、聞いていることは見えていないといけない。
   */
  | "following"
  | "error";

export interface Source {
  uri: string;
  title: string;
}

/** サーバーからデバイスへ送る JSON。 */
export type ServerMessage =
  | { type: "state"; state: DeviceState; status: string }
  /** 聞き取った内容。画面の上に出す。 */
  | { type: "question"; text: string }
  /** 回答の**累積全文**。差分ではないので、そのまま置き換えればよい。 */
  | { type: "answer"; text: string }
  | { type: "sources"; sources: Source[] }
  /**
   * 表情。**読み上げの直前に、その文の感情を送る。**
   *
   * 音より先に届くので、声が出るときには顔が変わっている。
   * 届かなくても会話は成り立つ（デバイスは前の表情のまま）。
   */
  | { type: "emotion"; emotion: Emotion }
  | { type: "error"; message: string }
  /**
   * 次に届くバイナリが読み上げの音声であることの予告。
   *
   * **表情もここに載せる。** 別々に送ると、鳴り終わりを知らない
   * サーバー側では順序を合わせられず、**顔だけ先に進む**
   * （実機で「音と感情がずれる」）。同じ予告に入れておけば、
   * 端末がその音を鳴らし始めるときに顔を変えられる。
   */
  | { type: "audio"; bytes: number; emotion?: Emotion }
  /**
   * 読み上げはこれで終わり。**次の音は来ない。**
   *
   * 端末は「キューが空になった」だけでは判断できない。文ごとに送るので、
   * 1 文目を鳴らし終えた時点で 2 文目がまだ届いていないことがあり、
   * **まだ喋る途中なのに鳴り終わりと報告してしまう**（実機で追い質問の
   * 窓が早く開き、自分の読み上げを拾って話が遮られた）。
   */
  | { type: "speech-end" }
  /** 設定の表示用（画面下の「いま Haiku 4.5」）。 */
  | { type: "config"; provider: string; model: string; wakeWords: string[] }
  /** どのチャットに入ったか。Web UI が履歴を追えるように。 */
  | { type: "chat"; chatId: string; title: string }
  /**
   * ウェイクワードで起こされた。
   *
   * **`state` の遷移では代わりにならない。** 追い質問の窓から
   * 呼び直したときも `listening` に入るので、どちらでウェイクワードが
   * 効いたのかが区別できない。効果音はこの合図だけで鳴らす。
   */
  | { type: "wake" }
  /**
   * 試験用（`?mode=wake`）。窓を1つ判定した結果。
   *
   * 誤起動を測るために**当たらなかった窓も送る**。何と聞こえたかが
   * 見えないと、語を選び直す材料にならない。
   */
  | {
      type: "heard";
      /** 書き起こし。無音なら空。 */
      text: string;
      /** 判定語に当たったか。 */
      fired: boolean;
      /** ISO8601 */
      at: string;
      /** 書き起こしにかかった時間（ミリ秒）。 */
      ms: number;
    };

/** デバイスからサーバーへ送る JSON（音声はバイナリで別に送る）。 */
export type DeviceMessage =
  /** 画面を触った / 物理ボタン。ウェイクワード無しで起こす。 */
  | { type: "wake" }
  /** やめる。 */
  | { type: "cancel" }
  /**
   * 読み上げを鳴らし終えた。**追い質問の窓はこれを合図に開く。**
   *
   * サーバーは WAV の長さから終わりを計算していたが、実際の再生とは
   * ずれる（**鳴り始めも鳴り終わりも、正確に知っているのは端末だけ**）。
   * 早く開くと自分の声を拾い、遅いと話しかけても反応しない時間ができる。
   */
  | { type: "spoken" }
  /**
   * 試験用（`?mode=wake`）。判定に使う語を差し替える。
   *
   * **設定（/admin）は書き換えない。** この接続の中だけで効く。
   * 同じ部屋の音に対して候補を比べられるようにするため。
   * 送らなければ設定の語を使う。
   */
  | { type: "wake-words"; words: string[] };
