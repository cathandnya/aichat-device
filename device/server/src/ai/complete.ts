/**
 * 話し終わったかの判定。**書き起こしの末尾を見る。**
 *
 * 無音 700ms で切ると、考えながら話す人の発話が途中で送られてしまう
 * （「冷蔵庫に卵と…」で切れて、AI が半端な質問に答える）。かといって
 * 無音の長さを一律に伸ばすと、**言い切ったときも必ず待たされる**。
 *
 * ### なぜ「完了したか」で見るか ★
 *
 * 「まだ続くか」を当てにいくと、続く形を無限に列挙することになる。
 * 日本語は**終わりの形のほうが閉じている**（終止形・丁寧体・終助詞）ので、
 * 「完了していなければ待つ」と書くほうが短く、外れ方も安全になる。
 *
 *   完了を見落とす → 少し待つ。続きが無ければ結局送られる（損は 1.5 秒）
 *   継続を見落とす → **話を切られる** ← 直したいのはこちら
 *
 * 迷ったときに**待つ側へ倒れる**のが、この向きの判定の取り柄。
 */

/**
 * 言い切りの形。ここで終わっていれば、そのまま送ってよい。
 *
 * **末尾から見る。** 文の途中に出ても意味がない。
 */
const COMPLETE = [
  // **句点は根拠にしない。**
  //
  // `ohr`（macOS の音声認識）は、途中で切れた音声にも文として句点を
  // 付ける。実測で「えっと。」が返り、**言い淀みが完了と判定された**。
  // 「。」を当てにすると、この判定は常に true になって意味を失う。
  //
  // 感嘆符と疑問符は残す。こちらは言い切った文にしか付かない。
  "！",
  "!",
  "？",
  "?",
  // 丁寧体
  "です",
  "です、",
  "ます",
  "ました",
  "ません",
  "でした",
  "ましょう",
  "ください",
  "くださる",
  // 終止形
  "だ",
  "である",
  // **過去形の「た」。** 「終わった」「見た」「買った」。
  // 「〜たら」は INCOMPLETE 側で先に拾うので、ここに置いてよい。
  "た",
  "する",
  "ない",
  "たい",
  "いる",
  "ある",
  "なる",
  "れる",
  "られる",
  // 終助詞。**「〜なのだ」「〜だよね」で終わる話し言葉を拾う。**
  "か",
  "かな",
  "ね",
  "よ",
  "な",
  "わ",
  "ぞ",
  "さ",
  "けど",
  "でしょ",
  "でしょう",
  // 依頼・命令
  "して",
  "教えて",
  "ちょうだい",
];

/**
 * 明らかに続く形。**ここで終わっていたら待つ。**
 *
 * `COMPLETE` に当たっても、こちらに当たればそちらを優先する
 * （「〜ですが」は `です` で終わっていないので本来当たらないが、
 * 「〜して、」のような形を確実に拾うため）。
 */
const INCOMPLETE = [
  // 接続助詞。**次に何か来る。**
  "が",
  "けれど",
  "けれども",
  "ので",
  "から",
  "のに",
  "たら",
  "れば",
  "ながら",
  "つつ",
  // 格助詞・並立。名詞のあとで切れている。
  "を",
  "に",
  "へ",
  "と",
  "や",
  "で",
  "は",
  "も",
  "の、",
  // 連用中止。「〜して、」「〜で、」
  "て",
  "、",
  "，",
  // **「の」は待つ側。** 「どうするの」（終助詞）と「今日の夕飯の」
  // （連体修飾）が同じ形で、実測では後者で切られた。外したときの
  // 損が小さいほうに倒す。
  "の",
  // 言いよどみ
  "えーと",
  "えーっと",
  "ええと",
  "あの",
  "あのー",
  "そのー",
  "なんか",
  "うーん",
];

/**
 * 話し終わったとみなせるか。
 *
 * **空なら「終わった」を返す。** 何も聞き取れていないときに待ち続けても
 * 意味がない（呼びかけただけの経路は別に用意してある）。
 */
/**
 * 依頼の言い切り。**「〜して」で終わるが、これは完了。**
 *
 * `INCOMPLETE` の「て」（連用中止）より先に見る。「買い物に行って」は
 * 続きがありそうだが、「教えて」「やめて」は言い切っている。
 * **動詞ごとに列挙する**しかないので、よく使うものだけ入れる。
 */
const REQUEST = [
  "教えて",
  "おしえて",
  "やめて",
  "止めて",
  "見せて",
  "調べて",
  "help",
];

export function looksComplete(text: string): boolean {
  // **末尾の句点を落としてから見る。** 書き起こしが機械的に付けるので、
  // 「えっと。」の「。」に意味は無い。語尾の形だけで判断する。
  const trimmed = text.trim().replace(/[。．]+$/, "");
  if (!trimmed) return true;

  // 依頼の言い切りは、連用中止の「て」より先に見る。
  if (REQUEST.some((word) => trimmed.endsWith(word))) return true;
  // **未完了が優先。** 「して、」は `て` でも `、` でも当たる。
  if (INCOMPLETE.some((word) => trimmed.endsWith(word))) return false;
  if (COMPLETE.some((word) => trimmed.endsWith(word))) return true;

  // どちらでもない。**名詞やカタカナで終わっている**ことが多く、
  // 「東京の」「明日の天気」のように続きがありうる。待つ側に倒す。
  return false;
}
